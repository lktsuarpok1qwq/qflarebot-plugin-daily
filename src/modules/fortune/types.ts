export const LEVELS = { great: [85, 100], good: [70, 84], small: [55, 69], neutral: [40, 54], bad: [20, 39], worst: [0, 19] } as const;
export const RARITIES = ["common", "rare", "epic", "legendary"] as const;
export const THEMES = ["absurd", "cyber", "gaming", "daily", "student", "mystic"] as const;
export type Level = keyof typeof LEVELS;
export type Rarity = typeof RARITIES[number];
export type Theme = typeof THEMES[number];
type Entry = { id: string; weight: number; tags: string[] };
export type FortuneEntry = Entry & { level: Level; rarity: Rarity; theme: Theme; title: string; sign: string; explanation: string };
export type ActionEntry = Entry & { kind: "good" | "bad"; text: string };
export type EffectEntry = Entry & { type: "buff" | "debuff"; name: string; description: string };
export type LuckyItem = Entry & { name: string; description: string };
export type EasterEgg = Entry & { text: string; dates?: string[]; weekdays?: number[] };
export type FortuneCorpus = { fortunes: FortuneEntry[]; actions: ActionEntry[]; effects: EffectEntry[]; items: LuckyItem[]; eggs: EasterEgg[]; eggChance: number };
export type DrawSettings = Record<`level_${Level}` | `rarity_${Rarity}`, number> & Record<`theme_${Theme}` | "eggs", boolean>;
export type FortuneResult = { date: string; entry: FortuneEntry; score: number; good: ActionEntry[]; bad: ActionEntry[]; effect?: EffectEntry; item?: LuckyItem; egg?: EasterEgg };
export type FortuneDocument = { kind: "help" | "noIdentity" | "unavailable" } | { kind: "draw"; result: FortuneResult };
